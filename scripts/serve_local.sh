#!/usr/bin/env bash
#
# يشغّل خادم مآثر على الماك ويفحص نفسه ثم يعرض رمز اقتران.
#
#     bash scripts/serve_local.sh
#
# ## لماذا هذا الملف موجود
#
# قضينا مساءً كاملاً على عطبٍ سببه بسيط: **الخادم يحمل الكود الذي أُقلع به.**
# فبقي يعمل بنسخة سابقة لإضافة مسار التسجيل، ويعيد 404 على كل محاولة، بينما
# يقول التطبيق «انتهى أو استُعمل» — فتُولَّد رموز بلا فائدة والسبب في مكان آخر.
#
# ثم أُغلقت الطرفية فمات الخادم معها.
#
# فهذا الملف يحسم الأمرين: يقتل القديم دائماً، ويشغّل الجديد **مفصولاً عن
# الطرفية** (`nohup`) فلا يموت بإغلاقها، **ثم يفحص المسار فعلاً قبل أن يعد
# بشيء**. لا «✅ يعمل» بلا دليل — الدرس نفسه الذي علّمنا إياه `expo prebuild`.
#
# ## ما لا يفعله
#
# لا يفتح منفذاً على الإنترنت: الاستماع يبقى `127.0.0.1`، والوصول من الجوال
# عبر الشبكة الخاصة وحدها.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND="$ROOT/backend"
LOG="$ROOT/data/server.log"
BASE="${MAATHER_BACKEND_URL:-https://maathers-macbook-pro.taildd422e.ts.net}"
LOOPBACK="http://127.0.0.1:8000"

red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }
dim()   { printf '\033[2m%s\033[0m\n' "$*"; }

probe() {
  # يطبع رمز الحالة وحده. تحدٍّ وهمي: **لا يستهلك رمزاً حقيقياً.**
  # لا `|| echo 000`: curl يطبع 000 بنفسه عند فشل الاتصال، فتجتمع القيمتان.
  local out
  out="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 \
    -X POST -H 'content-type: application/json' \
    -d '{"challenge_id":"probe","public_identity":"aaaaaaaa","device_name":"probe"}' \
    "$1/api/mobile/session/enroll" 2>/dev/null)"
  echo "${out:-000}"
}

# ---------------------------------------------------------------------------
# ١ — إيقاف الخادم القديم
# ---------------------------------------------------------------------------
# **بالمنفذ لا بمطابقة الاسم.** `pkill -f` يطابق سطر الأمر، فيقتل أي عملية
# يظهر فيها النصّ — بما فيها صدفةٌ تشغّل هذا الملف نفسه. حدث ذلك في التجربة.
# و«من يمسك المنفذ» هو المقصود بالضبط.
old_pids="$(lsof -ti tcp:8000 -sTCP:LISTEN 2>/dev/null || true)"
if [ -n "$old_pids" ]; then
  # shellcheck disable=SC2086
  kill $old_pids 2>/dev/null || true
  dim "  أُوقف خادم سابق كان يمسك المنفذ 8000."
  sleep 1
fi

# ---------------------------------------------------------------------------
# ٢ — تشغيل الجديد مفصولاً عن الطرفية
# ---------------------------------------------------------------------------
cd "$BACKEND" || { red "⛔ لم أجد مجلّد backend."; exit 1; }

if [ ! -f .venv/bin/activate ]; then
  red "⛔ البيئة الافتراضية غير موجودة في backend/.venv"
  echo "   أنشئيها: python3 -m venv .venv && source .venv/bin/activate && pip install -r requirements.txt"
  exit 1
fi
# shellcheck disable=SC1091
source .venv/bin/activate

mkdir -p "$(dirname "$LOG")"
nohup uvicorn app.main:app --host 127.0.0.1 --port 8000 >>"$LOG" 2>&1 &
server_pid=$!
disown 2>/dev/null || true
dim "  أُقلع الخادم (pid $server_pid) · السجل: data/server.log"

# ---------------------------------------------------------------------------
# ٣ — انتظار الجاهزية — **بالفحص لا بالنوم الأعمى**
# ---------------------------------------------------------------------------
ready=0
for _ in $(seq 1 40); do
  if [ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 "$LOOPBACK/api/mobile/v1/describe" 2>/dev/null)" = "200" ]; then
    ready=1
    break
  fi
  sleep 0.5
done

if [ "$ready" -ne 1 ]; then
  red "⛔ الخادم لم يقلع خلال 20 ثانية. آخر ما في السجل:"
  tail -n 15 "$LOG"
  exit 1
fi
green "✅ الخادم يعمل ويستمع على 127.0.0.1:8000"

# ---------------------------------------------------------------------------
# ٤ — هل مسار التسجيل موجود فعلاً؟ (هذا ما فشل من قبل)
# ---------------------------------------------------------------------------
local_code="$(probe "$LOOPBACK")"
case "$local_code" in
  401) green "✅ مسار التسجيل موجود ويرفض التحدّي الوهمي كما يجب." ;;
  404) red "⛔ مسار التسجيل غير موجود في هذه النسخة من الكود."
       echo "   حدّثي المستودع (git log --oneline -1) — يجب أن يكون 0.6.0 أو أحدث."
       exit 1 ;;
  *)   red "⛔ ردّ غير متوقَّع من مسار التسجيل: $local_code"; exit 1 ;;
esac

# ---------------------------------------------------------------------------
# ٥ — وهل يصل الجوال إليه؟ الفحص على **الطريق الذي يسلكه الجوال فعلاً**
# ---------------------------------------------------------------------------
remote_code="$(probe "$BASE")"
case "$remote_code" in
  401) green "✅ الشبكة الخاصة توصل الجوال إلى الخادم." ;;
  404) red "⛔ الوسيط يصل إلى خادم آخر — غالباً نسخة قديمة ما زالت تعمل."
       echo "   أوقفي كل خوادم uvicorn ثم أعيدي تشغيل هذا الأمر."
       exit 1 ;;
  502|000)
       red "⛔ لا يوجد وسيط يستقبل على $BASE"
       echo "   شغّلي في نافذة أخرى:"
       echo "     tailscale serve --bg 8000"
       exit 1 ;;
  *)   red "⛔ ردّ غير متوقَّع عبر الشبكة الخاصة: $remote_code"; exit 1 ;;
esac

# ---------------------------------------------------------------------------
# ٦ — والآن فقط: رمز الاقتران
# ---------------------------------------------------------------------------
echo
python3 -m app.mobile.pairing --backend "$BASE"
echo
dim "  الخادم يبقى يعمل بعد إغلاق هذه النافذة."
dim "  لإيقافه:  kill \$(lsof -ti tcp:8000 -sTCP:LISTEN)"
