#!/usr/bin/env bash
#
# التشغيل الكامل — يُنفَّذ على الماك، ويقوم بكل شيء بترتيبٍ واحد:
#
#     bash scripts/wake_and_run.sh
#
# ## لماذا سكربت واحد لا سبعة أوامر
#
# كل خطوة هنا مشروطة بنجاح ما قبلها. ولو نُفِّذت يدوياً، كفى أن تُتخطّى
# واحدة أو تُقرأ نتيجتها خطأً ليصير التشخيص لاحقاً بحثاً في العتمة.
# والسكربت يتوقّف عند أول إخفاق ويقول أين وقف — ولا يطبع نجاحاً لم يحدث.
#
# ## ما لا يفعله
#
# لا يفتح قفلاً، ولا يرفع «موقوف محلياً»، ولا يرسل أمراً إلى أي وسيط.
# المحاكاة في الخطوة ٦ تقرأ التاريخ وتقرّر على الورق فقط.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1
PY="$ROOT/backend/.venv/bin/python"
LOG="$ROOT/data/wake-run-$(date +%Y%m%d-%H%M).log"
mkdir -p "$(dirname "$LOG")"

red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }
step()  { printf '\n\033[1m▸ %s\033[0m\n' "$*"; }
fail()  { red "⛔ توقّف عند: $*"; red "   السجلّ: $LOG"; exit 1; }

exec > >(tee -a "$LOG") 2>&1
echo "بدأ: $(date)"

# ---------------------------------------------------------------------------
step "١ · فحص المتطلّبات"
# ---------------------------------------------------------------------------
[ -x "$PY" ] || fail "بيئة بايثون غير موجودة: $PY"
[ -d "$ROOT/_identity_bundle" ] || fail "حزمة الهوية غير مفكوكة في _identity_bundle/"
command -v npx >/dev/null || fail "npx غير موجود"
green "✅ جاهز"

# ---------------------------------------------------------------------------
step "٢ · فحص الهوية قبل الإنزال"
# ---------------------------------------------------------------------------
"$PY" scripts/land_identity.py || fail "فحص الهوية — النسق لا يطابق. لم يُكتب شيء."

# ---------------------------------------------------------------------------
step "٣ · إنزال الهوية"
# ---------------------------------------------------------------------------
"$PY" scripts/land_identity.py --apply || fail "إنزال الهوية"

# ---------------------------------------------------------------------------
step "٤ · اختبارات الجوال"
# ---------------------------------------------------------------------------
( cd mobile && npx jest --silent ) || fail "اختبارات الجوال"
green "✅ خضراء"

# ---------------------------------------------------------------------------
step "٥ · اختبارات الخلفية"
# ---------------------------------------------------------------------------
# الخط الأساسي المعروف: ٤ إخفاقات بيئية موثّقة. أي زيادة عليها انحدار.
( cd backend && "$PY" -m pytest -q 2>&1 | tail -6 )
FAILED=$( cd backend && "$PY" -m pytest -q 2>&1 | grep -oE '^[0-9]+ failed' | grep -oE '^[0-9]+' || echo 0 )
if [ "${FAILED:-0}" -gt 4 ]; then
  fail "الخلفية: $FAILED إخفاقاً — أكثر من الخط الأساسي (٤)"
fi
green "✅ لا انحدار (${FAILED:-0} إخفاقاً، والخط الأساسي ٤)"

# ---------------------------------------------------------------------------
step "٦ · المحاكاة على التاريخ الكامل"
# ---------------------------------------------------------------------------
# قراءة وتقرير فقط. لا أمر يُرسل، ولا قفل يُفتح.
# --full-history لم تكن راية موجودة في run_backtest — تحقّقتُ من --help.
# المسح الحقيقي في سكربت مستقلّ ينزل في الزمن نداءً بعد نداء.
"$PY" scripts/run_history_sweep.py --source live \
  --report "$ROOT/data/history-sweep-$(date +%Y%m%d).json" \
  || red "⚠️  المسح لم يكتمل — انظري السجلّ. الخطوات ١-٥ سليمة."

# ---------------------------------------------------------------------------
step "٧ · تجهيز البناء"
# ---------------------------------------------------------------------------
green "الاختبارات خضراء والهوية منزَّلة. لبناء التطبيق على الجوال:"
echo ""
echo "    cd mobile && npx expo prebuild --clean && open ios/*.xcworkspace"
echo ""
echo "  ثم Run في Xcode. سيُطلب مسح رمز الاقتران مرّة واحدة — بناءٌ جديد"
echo "  يمحو التخزين الآمن على الجهاز، وهذا متوقَّع لا عطل."
echo ""
green "انتهى: $(date)"
echo "السجلّ الكامل: $LOG"
