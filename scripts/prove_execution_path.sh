#!/usr/bin/env bash
#
# إثبات مسار التنفيذ — **يُشغَّل على الماك**، بأمرٍ واحد.
#
#     bash scripts/prove_execution_path.sh "أوافق على أمر تجريبي واحد"
#
# ## لماذا يوجد هذا السكربت
#
# لأن الخطوات ثلاث ومتتابعة، وكل واحدة بلا سابقتها تكذب:
#
#   نشر ⇐ إعادة تشغيل فعلية ⇐ مسبار
#
# فمسبارٌ يُشغَّل بلا نشر يقيس كوداً قديماً، وقد كلّفنا ذلك ليلةً كاملة حين
# خدمت عمليةٌ واحدة (35389) بكودٍ عمره ساعات عبر خمس نشرات. ولذلك يتحقّق
# هذا السكربت من **رقم العملية والكوميت العامل** قبل أن يقيس شيئاً.
#
# ## وما لا يفعله
#
#   * لا يكتب العبارة عنك. **الموافقة تُمرَّر بيدك في كل مرّة** — وسورٌ
#     يحمل عبارته في جيبه ليس سوراً.
#   * لا يفتح مركزاً. المسبار أمرٌ معلَّق بعيدٌ عن السوق، يُلغى في `finally`.
#   * لا يقلب `STOP_DISTANCE_UNIT_PROVEN`. يطبع القياس، والقلب قرارٌ بعده.
set -uo pipefail

APPROVAL="${1:-}"
SERVER_IP="${2:-167.233.234.236}"
KEY="${MATHRAH_SSH_KEY:-$HOME/Desktop/Trading/.ssh-maather/maather_hetzner}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }
step()  { printf '\n\033[1m▸ %s\033[0m\n' "$*"; }
dim()   { printf '\033[2m%s\033[0m\n' "$*"; }

if [ -z "$APPROVAL" ]; then
  red "⛔ لا تشغيل بلا موافقة صريحة."
  echo '   bash scripts/prove_execution_path.sh "أوافق على أمر تجريبي واحد"'
  dim  "   المسبار يرسل أمراً معلَّقاً حقيقياً إلى الوسيط على حساب Demo، ثم يلغيه."
  exit 2
fi

# ---------------------------------------------------------------------------
step "١ · النشر — والكود الجديد يجب أن يصير هو العامل"
# ---------------------------------------------------------------------------
bash "$ROOT/scripts/deploy_to_server.sh" "$SERVER_IP" || {
  red "⛔ أخفق النشر. لا يُقاس شيء على كودٍ لم يصل."
  exit 1
}

# ---------------------------------------------------------------------------
step "٢ · التحقّق: أهو الكوميت الذي بين يدينا فعلاً؟"
# ---------------------------------------------------------------------------
EXPECTED="$(git -C "$ROOT" rev-parse HEAD)"
RUNNING="$(ssh -i "$KEY" -o StrictHostKeyChecking=accept-new "root@$SERVER_IP" \
  "curl -s http://127.0.0.1:8000/api/version" 2>/dev/null \
  | sed -n 's/.*"commit":"\([^"]*\)".*/\1/p')"

if [ -z "$RUNNING" ]; then
  red "⛔ الخدمة لم تُجب على /api/version. لا قياس على خدمةٍ مجهولة الإصدار."
  exit 1
fi
if [ "${RUNNING:0:7}" != "${EXPECTED:0:7}" ]; then
  red "⛔ الخدمة تعمل بـ ${RUNNING:0:7} والمتوقَّع ${EXPECTED:0:7}."
  red "   هذا هو العطل الذي كلّفنا ليلة. لا يُمضى."
  exit 1
fi
green "✅ الخدمة تعمل بـ ${RUNNING:0:7} — وهو ما نقيس عليه."

# ---------------------------------------------------------------------------
step "٣ · المسبار — أمرٌ معلَّق واحد، يُلغى في كل الأحوال"
# ---------------------------------------------------------------------------
ssh -i "$KEY" "root@$SERVER_IP" \
  "cd /opt/mathrah/backend && sudo -u mathrah /opt/mathrah/.venv/bin/python \
   -m app.diagnostics.stop_distance_probe --approve '$APPROVAL'"
RC=$?

echo
if [ $RC -eq 0 ]; then
  green "✅ القياس تمّ. أرسلي المخرَج كاملاً — القلب قرارٌ بعده، لا فيه."
else
  red "○ لم يكتمل القياس (رمز $RC). المخرَج أعلاه يحمل سبب الوسيط بلسانه."
fi
exit $RC
