/**
 * هوية الجهاز المُعلَنة عند التسجيل.
 *
 * ## ما هي بالضبط — وما ليست
 *
 * **ليست مفتاحاً عاماً**، ولا تقوم عليها أي مصادقة. هي معرّف عشوائي يُولَّد
 * مرة واحدة على الجهاز ويُحفَظ في سلسلة المفاتيح، والخادم يخزّن **بصمته
 * SHA-256 لا قيمته**. فائدتها في التدقيق: تمييز جهازين لا إثبات هوية.
 *
 * والمصادقة كلها برموز الخادم قصيرة العمر. فلو تسرّبت هذه القيمة لم يمكن
 * لحاملها أن يسجّل جهازاً: التسجيل يحتاج تحدّياً وُلّد على الخادم قبل
 * دقيقتين ولم يُستهلَك.
 *
 * ## لماذا لا تُشتقّ من معرّف الجهاز
 *
 * معرّفات الأجهزة الثابتة تتيح الربط بين تطبيقات ومصادر مختلفة. وهذا
 * التطبيق لا يحتاجها: قيمة عشوائية خاصة به تكفي تماماً، ولا تتبع المالكة
 * إلى أي مكان آخر.
 *
 * ## مصدر العشوائية
 *
 * `expo-crypto` غير مثبَّتة، و`crypto.getRandomValues` غير متاحة في زمن
 * تشغيل React Native افتراضياً. والقيمة هنا **ليست سرّاً ولا مفتاحاً**، بل
 * معرّفاً يجب أن يكون فريداً لا غير متوقَّع. فيُبنى من الوقت بدقّة عالية
 * مع عشوائية إضافية — وهذا كافٍ للتفرّد، **وغير كافٍ لو كانت سرّاً**، ولذلك
 * لا يُبنى عليها أي قرار أمني.
 */
import { tokenStore } from './tokenStore';

const IDENTITY_LENGTH = 32;

const randomSuffix = (): string =>
  Array.from({ length: 4 }, () => Math.random().toString(36).slice(2, 10)).join('');

/**
 * يعيد الهوية المحفوظة، ويولّدها عند أول استدعاء.
 *
 * ثابتة عبر عمليات التسجيل: إعادة تسجيل الجهاز نفسه تُنتج البصمة نفسها على
 * الخادم، فيُقرأ في سجل التدقيق **جهازاً واحداً أُعيد تسجيله** لا جهازاً
 * جديداً — وهو ما حدث فعلاً.
 */
export async function publicIdentity(): Promise<string> {
  const existing = await tokenStore.loadPublicIdentity();
  if (existing !== null && existing.length >= 8) {
    return existing;
  }
  const generated = `${Date.now().toString(36)}${randomSuffix()}`.slice(0, IDENTITY_LENGTH);
  await tokenStore.savePublicIdentity(generated);
  return generated;
}
