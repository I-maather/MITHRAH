"""
ما تشترك فيه استراتيجيات الفوركس الثلاث.

## القاعدة التي تحكمها جميعاً: لكلٍّ ظرفٌ تعمل فيه، وحارسٌ يمنعها خارجه

`TREND_PULLBACK v1` تدخل في **أي** سوق: لا شيء فيها يسأل «أهذا سوقٌ ممتدّ أم
عرضي؟». وفكرةٌ تربح في اتجاهٍ ممتدّ تخسر في سوقٍ عرضي بالضرورة — فاستراتيجيةٌ
بلا حارس ظرفٍ ليست استراتيجيةً واحدة، هي واحدةٌ صحيحة وأخرى خاطئة تعملان
بالاسم نفسه ويُجمع أداؤهما فيُلغي بعضه بعضاً.

فكل استراتيجية هنا تُعلن ظرفها وتُفحَص عليه بـ`ADX`:

    TREND_PULLBACK v2      ADX > 25   اتجاهٌ ممتدّ
    RANGE_MEAN_REVERSION   ADX < 20   سوقٌ عرضي
    BREAKOUT_RETEST        ضغطٌ ثم اتّساع

⇒ الثلاثة **لا تُشير في نفس الظرف**، فوجودها معاً يوسّع التغطية ولا يكرّرها.

## قيدٌ ظُنّ أنه يحكم الإطار الزمني — وكان خطأ وحدة

كُتب هنا (2026-09-01) أن أدنى مسافة وقف يقبلها كابيتال على EUR/USD تساوي
`0.01` **بوحدة السعر** = ١٠٠ نقطة، وبُني على ذلك الاستنتاج التالي بحروفه:

> «هذه الاستراتيجيات على الشمعة اليومية. والتداول داخل اليوم على هذا الوسيط
> ليس خياراً هندسياً بل يحتاج أداةً مختلفة أو وسيطاً مختلفاً.»

**والمقدّمة خاطئة.** الوسيط يعيد القاعدة بوحدتها:

    "minStopOrProfitDistance": {"unit": "PERCENTAGE", "value": 0.01}

أي **٠٫٠١٪ من السعر**. وعلى 1.16292 ذلك `0.000116` = **١٫١٦ نقطة**، لا مئة.
وقُرئت مدّةً سعراً خاماً لأن القارئ كان يأخذ `value` ويطرح `unit`.

القياس المباشر من حساب Demo (2026-09-03):

| الأداة | القاعدة | السعر | الحدّ الحقيقي |
|---|---|---|---|
| EURUSD | PERCENTAGE 0.01 | 1.16292 | 1.16 نقطة |
| GBPUSD | PERCENTAGE 0.01 | 1.35281 | 1.35 نقطة |
| USDJPY | PERCENTAGE 0.01 | 155.736 | 1.56 نقطة |
| GOLD   | PERCENTAGE 0.001 | 4472.63 | 4.47 (بحجم نقطة 0.01) |

⇒ وقفُ الساعة (`1.5×ATR ≈ 0.0015` = ١٥ نقطة) **فوق الحدّ بثلاثة عشر ضعفاً**،
ووقفُ ربع الساعة (≈ ٦ نقاط) فوقه بخمسة أضعاف. فالتداول داخل اليوم على هذا
الوسيط **مفتوحٌ هندسياً**، وقد أُغلق سنةً بخطأ وحدة.

وهذا أثرٌ أبعد من رفض الأوامر: **خطأ القياس شكّل قرار التصميم نفسه.** فصار
الإطار اليومي «قيداً من الوسيط» وهو ليس كذلك، وصار سقفُ تواتر الصفقات
نحو صفقةٍ كل أسبوعين — وهو أصل استحالة «صفقةٍ في كل يوم تداول».

**وما لم يتغيّر:** فتحُ الإطار لا يعني حافّةً فيه. مسحُ التاريخ يقيس
الاثنين منفصلين — التواتر والحافّة — ولا يُشغَّل إطارٌ إلا بدليلٍ مُسمّى
(`StrategyMetadata.approved_timeframes`) أو باستثناءٍ تجريبيٍّ موسوم.

ولا يُوسَّع الوقف تلقائياً هنا ولا في المحوّل: التوسيع يغيّر المخاطرة التي
وافقت عليها المالكة، فيُرفَض ويُقال السبب.
"""
from __future__ import annotations

from decimal import Decimal
from typing import Optional, Sequence

from ..contracts import Bar
from ..money import D

#: الأدوات التي اكتُشفت قواعدها من الوسيط فعلاً. لا تُضاف أداة بلا اكتشاف:
#: حجم النقطة وأدنى مسافة وقف والكمية الدنيا تختلف بينها اختلافاً جوهرياً.
FX_MARKETS: tuple[str, ...] = ("EURUSD", "GBPUSD", "USDJPY", "GOLD")

#: عتبات الظرف. أرقام ويلدر الشائعة، وتُراجَع بالقياس لا بالذوق.
TRENDING_ADX = D("25")
RANGING_ADX = D("20")


def closes(bars: Sequence[Bar]) -> list[Decimal]:
    return [b.close for b in bars]


def reward_risk(entry: Decimal, stop: Decimal, target: Decimal) -> Optional[Decimal]:
    """نسبة العائد إلى المخاطرة قبل التكاليف. تُعاد `None` لمخاطرةٍ صفرية."""
    risk = abs(entry - stop)
    if risk <= 0:
        return None
    return abs(target - entry) / risk


def sane_levels(*, entry: Decimal, stop: Decimal, target: Decimal, long: bool) -> bool:
    """
    فحصُ اتّجاهٍ لا فحصُ قيمة: في الشراء يقع الوقف **تحت** الدخول والهدف
    فوقه، وفي البيع العكس. وانعكاسُ أحدهما يُنتج أمراً يُنفَّذ فوراً بخسارة
    — وهو خطأٌ لا يظهر في أي اختبارٍ لا ينظر إلى الاتجاه.
    """
    if stop <= 0 or target <= 0 or entry <= 0:
        return False
    return (stop < entry < target) if long else (target < entry < stop)


